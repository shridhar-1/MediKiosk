const PAIN_COMPLAINTS = new Set(["chest_pain", "abdomen", "headache", "joint", "injury"]);
const FEVER_COMPLAINTS = new Set(["fever"]);

export function questionById(id: string): Question | undefined {
  return QUESTIONS.find((q) => q.id === id);
}

export function firstQuestionId(): string {
  return "chief_complaint";
}

export function nextQuestionId(
  currentId: string,
  answers: Record<string, { values: string[]; text: string }>,
  mode: CareMode,
): string | null {
  const chief = answers.chief_complaint?.values[0] ?? "";
  const isPain = PAIN_COMPLAINTS.has(chief);
  const isFever = FEVER_COMPLAINTS.has(chief);

  const sequence: string[] = ["chief_complaint"];
  if (chief === "other") sequence.push("other_complaint");
  sequence.push("duration", "onset", "course");
  if (isPain || chief === "chest_pain") {
    sequence.push("pain_site", "pain_character", "pain_radiation", "severity", "aggravating", "relieving");
  }
  if (isFever) sequence.push("fever_pattern");
  sequence.push("associated", "pmh", "surgery");
  if (answers.surgery?.values.includes("yes")) sequence.push("surgery_detail");
  sequence.push("medications");
  if (answers.medications?.values.includes("yes")) sequence.push("medications_detail");
  sequence.push("allergies");
  if (answers.allergies?.values.includes("yes")) sequence.push("allergies_detail");
  sequence.push("family", "tobacco", "alcohol", "diet_sleep", "occupation", "ros");
  if (mode === "ayush") {
    sequence.push("prakriti_body", "agni", "koshtha", "ahara", "vihara", "vyayama", "sattva", "nidana", "satmya");
  }

  const unique = [...new Set(sequence)];
  const idx = unique.indexOf(currentId);
  if (idx === -1) return unique[0] ?? null;
  return unique[idx + 1] ?? null;
}

function pathFor(
  answers: Record<string, { values: string[]; text: string }>,
  mode: CareMode,
): string[] {
  const path: string[] = [];
  let cursor: string | null = firstQuestionId();
  const guard = new Set<string>();
  while (cursor && !guard.has(cursor)) {
    path.push(cursor);
    guard.add(cursor);
    cursor = nextQuestionId(cursor, answers, mode);
  }
  return path;
}

export function previousQuestionId(
  currentId: string,
  answers: Record<string, { values: string[]; text: string }>,
  mode: CareMode,
): string | null {
  const path = pathFor(answers, mode);
  const idx = path.indexOf(currentId);
  if (idx <= 0) return null;
  return path[idx - 1] ?? null;
}

export function questionProgress(
  currentId: string,
  answers: Record<string, { values: string[]; text: string }>,
  mode: CareMode,
): { current: number; total: number } {
  const path = pathFor(answers, mode);
  const idx = Math.max(0, path.indexOf(currentId));
  return { current: idx + 1, total: Math.max(path.length, idx + 1) };
}

export function optionLabel(question: Question, optionId: string, lang: Lang): string {
  const opt = question.options?.find((o) => o.id === optionId);
  if (!opt) {
    if (optionId === "yes") return tx(YES, lang);
    if (optionId === "no") return tx(NO, lang);
    return optionId;
  }
  return tx(opt.label, lang);
}

export function formatAnswer(
  question: Question,
  values: string[],
  text: string,
  lang: Lang,
): string {
  if (question.type === "scale" && values[0]) return `${values[0]}/10`;
  if (question.type === "yesno") {
    if (values.includes("yes")) return tx(YES, lang);
    if (values.includes("no")) return tx(NO, lang);
  }
  const labels = values
    .filter((v) => v !== "yes" && v !== "no")
    .map((v) => optionLabel(question, v, lang));
  const parts = [...labels];
  if (text.trim()) parts.push(text.trim());
  return parts.join("; ") || "—";
}

export function matchSpokenToOptions(spoken: string, question: Question): string[] {
  const s = spoken.toLowerCase();
  if (question.type === "yesno") {
    if (/\b(yes|haan|ha|ஆம்|avunu|হ্যাঁ|ho|ಹೌದು)\b/i.test(s)) return ["yes"];
    if (/\b(no|nahi|na|illa|kadhu|না|नाही|ಇಲ್ಲ)\b/i.test(s)) return ["no"];
  }
  const hits: string[] = [];
  for (const opt of question.options ?? []) {
    const bag = Object.values(opt.label).join(" ").toLowerCase();
    if (bag.split(/[\s/,]+/).some((w) => w.length > 2 && s.includes(w.toLowerCase()))) {
      hits.push(opt.id);
    }
  }
  return hits;
}
